fn write_semantic_transition_catalogue(out_dir: &Path) {
    println!("cargo:rerun-if-changed=src/semantic_action_catalogue_v1.def");
    let path = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap())
        .join("src/semantic_action_catalogue_v1.def");
    let source = fs::read_to_string(path).expect("read semantic catalogue");
    let lines: Vec<String> = source
        .lines()
        .filter_map(|line| {
            let line = line
                .split('#')
                .next()
                .unwrap()
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" ");
            (!line.is_empty()).then_some(line)
        })
        .collect();
    let encoding = lines.join("\n") + "\n";
    let digest = catalogue_sha256(encoding.as_bytes());
    let mut constants = std::collections::BTreeMap::new();
    let mut fields = Vec::new();
    let mut roster = Vec::new();
    let mut declarations = Vec::new();
    let mut generation = None;
    let number = |s: &str| -> u64 {
        match s.strip_prefix("0x") {
            Some(hex) => u64::from_str_radix(hex, 16).expect("hex catalogue integer"),
            None => s.parse().expect("decimal catalogue integer"),
        }
    };
    for line in &lines {
        let parts: Vec<_> = line.split(' ').collect();
        match parts.as_slice() {
            ["generation", n] => {
                assert!(generation.replace(number(n)).is_none());
            }
            ["constant", name, value] => {
                assert!(constants.insert(*name, number(value)).is_none());
            }
            ["field", ordinal, name, role, cardinality] => {
                assert_eq!(number(ordinal) as usize, fields.len());
                fields.push((*name, *role, number(cardinality)));
            }
            ["roster", start, count, lane, kind, slot] => {
                roster.push((
                    number(start),
                    number(count),
                    number(lane),
                    *kind,
                    number(slot),
                ));
            }
            ["domain", name] => {
                assert_eq!(*name, "xlog.semantic-action-catalogue.v3");
            }
            [kind @ ("action" | "opcode"), value, name, signature @ ..] => {
                assert!(!signature.is_empty());
                assert!(declarations
                    .iter()
                    .all(|(k, v, n, _)| *k != *kind || (*v != number(value) && *n != *name)));
                declarations.push((*kind, number(value), *name, signature.join(" ")));
            }
            ["rule", name, meaning @ ..] => {
                assert!(!meaning.is_empty(), "empty catalogue rule {name}");
            }
            _ => panic!("invalid semantic catalogue declaration: {line}"),
        }
    }
    let generation = generation.expect("catalogue generation");
    assert_eq!(fields.len() as u64, constants["FIELD_COUNT"]);
    assert_eq!(fields[1].2, constants["SEMANTIC_OPCODE_CARDINALITY"]);
    let mut rust = format!("const CATALOGUE_ENCODING: &[u8] = {encoding:?}.as_bytes();\nconst CATALOGUE_DIGEST: [u8;32] = {digest:?};\nconst CATALOGUE_GENERATION: u64 = {generation};\n");
    let mut cuda = format!("#pragma once\n#include <stdint.h>\nstatic constexpr uint64_t CATALOGUE_GENERATION = {generation};\n__device__ __constant__ uint8_t CATALOGUE_DIGEST[32] = {{ {} }};\n",
        digest.iter().map(u8::to_string).collect::<Vec<_>>().join(","));
    // Both consumers receive the same values, field signatures, and row layout.
    for name in [
        "TEXT_CARDINALITY",
        "TEXT_NULL",
        "MASK_TOKEN",
        "SCRATCH_BYTES",
        "COMPONENT_COUNT",
        "COMPONENT_KIND_TEXT",
        "COMPONENT_KIND_EDIT",
        "SEMANTIC_OPCODE_CARDINALITY",
        "ACTION_BATCH_ABI",
        "NULL_CATEGORY",
        "NO_EDIT_ACTIVE_MASK",
        "NO_EDIT_NULL_MASK",
        "INSERT_SUPPORT_ACTIVE_MASK",
        "INSERT_SUPPORT_NULL_MASK",
        "INSERT_RULE_ACTIVE_MASK",
        "INSERT_RULE_NULL_MASK",
        "REPLACE_BRANCH_ACTIVE_MASK",
        "REPLACE_BRANCH_NULL_MASK",
        "REPLACE_LEAF_ACTIVE_MASK",
        "REPLACE_LEAF_NULL_MASK",
        "REPLACE_ROOT_ACTIVE_MASK",
        "REPLACE_ROOT_NULL_MASK",
        "REPLACE_WEIGHT_ACTIVE_MASK",
        "REPLACE_WEIGHT_NULL_MASK",
        "SEMANTIC_CATEGORY_CAPACITY",
    ] {
        if name != "NULL_CATEGORY" {
            rust.push_str(&format!("const {name}: usize = {};\n", constants[name]));
        }
        cuda.push_str(&format!(
            "static constexpr uint32_t {name} = {};\n",
            constants[name]
        ));
    }
    rust.push_str("const CATALOGUE_FIELDS: &[SemanticCatalogueField] = &[\n");
    cuda.push_str("struct CatalogueField { uint32_t ordinal, cardinality; const char *name, *role; };\n__device__ const CatalogueField CATALOGUE_FIELDS[] = {\n");
    for (index, (name, role, cardinality)) in fields.iter().enumerate() {
        assert!(*cardinality > 0 && *cardinality <= 65536);
        rust.push_str(&format!("SemanticCatalogueField {{ ordinal:{index}, cardinality:{cardinality}, name:{name:?}, role:{role:?} }},\n"));
        cuda.push_str(&format!(
            "{{{index}, {cardinality}, {name:?}, {role:?}}},\n"
        ));
    }
    rust.push_str("];\n");
    cuda.push_str("};\n");
    rust.push_str("const CATALOGUE_SIGNATURES: &[SemanticCatalogueSignature] = &[\n");
    cuda.push_str("struct CatalogueSignature { uint32_t value; const char *kind, *name, *signature; };\n__device__ const CatalogueSignature CATALOGUE_SIGNATURES[] = {\n");
    for (kind, value, name, signature) in &declarations {
        assert!(*value < 65536);
        for token in signature.split(' ').filter(|s| s.ends_with("_MASK")) {
            assert!(constants.contains_key(token), "undefined mask {token}");
        }
        rust.push_str(&format!("SemanticCatalogueSignature {{ value:{value}, kind:{kind:?}, name:{name:?}, signature:{signature:?} }},\n"));
        cuda.push_str(&format!(
            "{{{value}, {kind:?}, {name:?}, {signature:?}}},\n"
        ));
    }
    rust.push_str("];\n");
    cuda.push_str("};\n");
    rust.push_str("fn semantic_opcode_masks(value: u32) -> Option<(u32,u32)> { match value {\n");
    cuda.push_str("__device__ uint32_t semantic_opcode_active(uint32_t value) { switch(value) {\n");
    for (kind, value, _, signature) in &declarations {
        if *kind != "opcode" || *value == 0 {
            continue;
        }
        let masks: Vec<_> = signature.split(' ').collect();
        assert_eq!(masks.len(), 2);
        rust.push_str(&format!(
            "{value} => Some(({},{})),\n",
            constants[masks[0]], constants[masks[1]]
        ));
        cuda.push_str(&format!("case {value}: return {};\n", constants[masks[0]]));
    }
    rust.push_str("_ => None, } }\n");
    cuda.push_str("default: return 0; } }\n");
    cuda.push_str("__device__ uint32_t semantic_opcode_null(uint32_t value) { switch(value) {\n");
    for (kind, value, _, signature) in &declarations {
        if *kind != "opcode" || *value == 0 {
            continue;
        }
        let masks: Vec<_> = signature.split(' ').collect();
        cuda.push_str(&format!("case {value}: return {};\n", constants[masks[1]]));
    }
    cuda.push_str("default: return 0; } }\n");
    for (kind, name) in [("action", "NO_EDIT"), ("action", "APPLY")] {
        let value = declarations
            .iter()
            .find(|(k, _, n, _)| *k == kind && *n == name)
            .expect("required action declaration")
            .1;
        cuda.push_str(&format!(
            "static constexpr uint32_t ACTION_{name} = {value};\n"
        ));
    }
    let action_field = fields
        .iter()
        .position(|(name, _, _)| *name == "action_class")
        .expect("action class field");
    cuda.push_str(&format!(
        "static constexpr uint32_t ACTION_CLASS_FIELD = {action_field};\n"
    ));
    rust.push_str("const COMPONENTS: &[SemanticComponent] = &[\n");
    cuda.push_str("struct Component { uint64_t offset; uint32_t ordinal, lane, slot, field, kind, cardinality; };\n__device__ __constant__ Component COMPONENTS[] = {\n");
    let mut ordinal = 0;
    let mut offset = 0;
    for (start, count, lane, kind, slot) in roster {
        assert_eq!(start, ordinal, "noncontiguous catalogue roster");
        for field in 0..count {
            let (kind, cardinality) = match kind {
                "text" => (
                    constants["COMPONENT_KIND_TEXT"],
                    constants["TEXT_CARDINALITY"],
                ),
                "edit" => (constants["COMPONENT_KIND_EDIT"], fields[field as usize].2),
                _ => panic!("unknown component kind"),
            };
            rust.push_str(&format!("SemanticComponent {{ offset:{offset}, ordinal:{ordinal}, lane:{lane}, slot:{slot}, field:{field}, kind:{kind}, cardinality:{cardinality} }},\n"));
            cuda.push_str(&format!(
                "{{{offset}, {ordinal}, {lane}, {slot}, {field}, {kind}, {cardinality}}},\n"
            ));
            ordinal += 1;
            offset += cardinality;
        }
    }
    assert_eq!(ordinal, constants["COMPONENT_COUNT"]);
    rust.push_str("];\n");
    cuda.push_str("};\n");
    // Canonical rule bytes remain available to both bindings, including descriptor
    // roles and dependent arity rules used by the admitted device codebooks.
    cuda.push_str(&format!(
        "__device__ __constant__ char CATALOGUE_ENCODING[] = {encoding:?};\n"
    ));
    write_if_changed(out_dir.join("semantic_transition_catalogue.rs"), rust)
        .expect("write Rust catalogue");
    write_if_changed(out_dir.join("semantic_transition_catalogue.cuh"), cuda)
        .expect("write CUDA catalogue");
}

fn catalogue_sha256(bytes: &[u8]) -> [u8; 32] {
    Sha256::digest(bytes).into()
}

fn hash_field(hash: &mut Sha256, bytes: &[u8]) {
    hash.update((bytes.len() as u64).to_le_bytes());
    hash.update(bytes);
}

const KERNEL_SOURCE_DATE_EPOCH: &str = "0";

fn cuda_command(program: &Path) -> Command {
    let mut command = Command::new(program);
    // Kernel code has a reproducible compiler clock independent of the wheel's
    // release timestamp, so a new source revision does not invalidate every
    // unchanged CUDA object. The wheel retains its caller-supplied epoch.
    command.env("SOURCE_DATE_EPOCH", KERNEL_SOURCE_DATE_EPOCH);
    command
}

fn resolve_compiler(program: &Path) -> PathBuf {
    if program.components().count() > 1 || program.is_absolute() {
        return program.canonicalize().expect("resolve CUDA compiler");
    }
    for directory in env::split_paths(&env::var_os("PATH").unwrap_or_default()) {
        let candidate = directory.join(program);
        for candidate in [candidate.clone(), candidate.with_extension("exe")] {
            if candidate.is_file() {
                return candidate.canonicalize().expect("resolve compiler on PATH");
            }
        }
    }
    panic!("compiler not found: {}", program.display());
}

fn dependency_paths(output: &[u8]) -> Vec<PathBuf> {
    let text = std::str::from_utf8(output)
        .expect("NVCC dependency paths must be UTF-8")
        .replace("\\\r\n", "")
        .replace("\\\n", "");
    let (_, prerequisites) = text
        .split_once(':')
        .expect("NVCC must emit a Make dependency rule");
    let mut paths = BTreeSet::new();
    let mut path = String::new();
    let mut chars = prerequisites.chars().peekable();
    while let Some(character) = chars.next() {
        match character {
            '\\' => path.push(chars.next().expect("unfinished NVCC path escape")),
            '$' if chars.peek() == Some(&'$') => {
                chars.next();
                path.push('$');
            }
            c if c.is_whitespace() => {
                if !path.is_empty() {
                    paths.insert(PathBuf::from(std::mem::take(&mut path)));
                }
            }
            c => path.push(c),
        }
    }
    if !path.is_empty() {
        paths.insert(PathBuf::from(path));
    }
    assert!(!paths.is_empty(), "NVCC emitted no source dependencies");
    paths.into_iter().collect()
}

struct KernelCompiler {
    nvcc: PathBuf,
    ptxas: Option<PathBuf>,
    out_dir: PathBuf,
    kernels_dir: PathBuf,
    cubin_archs: Vec<String>,
    no_cubin: bool,
    semantic_policy: bool,
    compiler_key: [u8; 32],
    inputs: Mutex<BTreeMap<PathBuf, [u8; 32]>>,
    reused: AtomicUsize,
    compiled: AtomicUsize,
}

impl KernelCompiler {
    fn input_digest(&self, path: &Path) -> [u8; 32] {
        let path = path
            .canonicalize()
            .unwrap_or_else(|error| panic!("resolve build input {}: {error}", path.display()));
        let mut inputs = self.inputs.lock().expect("kernel input cache poisoned");
        *inputs.entry(path.clone()).or_insert_with(|| {
            let bytes = fs::read(&path)
                .unwrap_or_else(|error| panic!("read build input {}: {error}", path.display()));
            catalogue_sha256(&bytes)
        })
    }

    fn compiler_identity(&self) -> [u8; 32] {
        let mut hash = Sha256::new();
        hash_field(&mut hash, KERNEL_SOURCE_DATE_EPOCH.as_bytes());
        // Only the compiler's input closure is fingerprinted, never an artifact
        // archive, environment tree, source revision or downstream package.
        for compiler in std::iter::once(&self.nvcc).chain(self.ptxas.iter()) {
            hash_field(&mut hash, compiler.as_os_str().as_encoded_bytes());
            hash.update(self.input_digest(compiler));
            let version = cuda_command(compiler)
                .arg("--version")
                .output()
                .expect("read CUDA compiler version");
            assert!(version.status.success(), "CUDA compiler --version failed");
            hash_field(&mut hash, &version.stdout);
            hash_field(&mut hash, &version.stderr);
        }
        let toolkit = self.nvcc.parent().and_then(Path::parent).unwrap();
        for relative in [
            "bin/ptxas",
            "bin/cudafe++",
            "bin/fatbinary",
            "bin/nvlink",
            "nvvm/bin/cicc",
            "version.json",
        ] {
            let path = toolkit.join(relative);
            if path.is_file() {
                hash.update(self.input_digest(&path));
            }
        }
        let libdevice = toolkit.join("nvvm/libdevice");
        if libdevice.is_dir() {
            let mut paths = fs::read_dir(libdevice)
                .expect("read CUDA device library directory")
                .map(|entry| entry.expect("read CUDA device library entry").path())
                .filter(|path| path.extension().is_some_and(|extension| extension == "bc"))
                .collect::<Vec<_>>();
            paths.sort();
            for path in paths {
                hash.update(self.input_digest(&path));
            }
        }
        let host = env::var_os("NVCC_CCBIN").unwrap_or_else(|| {
            if cfg!(windows) {
                "cl".into()
            } else {
                "g++".into()
            }
        });
        hash.update(self.input_digest(&resolve_compiler(Path::new(&host))));
        for name in [
            "PATH",
            "NVCC_CCBIN",
            "NVCC_PREPEND_FLAGS",
            "NVCC_APPEND_FLAGS",
            "CPATH",
            "C_INCLUDE_PATH",
            "CPLUS_INCLUDE_PATH",
        ] {
            println!("cargo:rerun-if-env-changed={name}");
            hash_field(
                &mut hash,
                env::var_os(name).unwrap_or_default().as_encoded_bytes(),
            );
        }
        hash.finalize().into()
    }

    fn nvcc_args(&self, name: &str, arch: &str) -> Vec<String> {
        let mut args = vec![
            format!("-I{}", self.out_dir.display()),
            format!("-arch={arch}"),
            "-O3".to_owned(),
        ];
        push_common_nvcc_options(&mut args, name);
        push_semantic_policy_options(&mut args, name, self.semantic_policy);
        push_wcoj_register_cap(&mut args, name);
        args.push(
            self.kernels_dir
                .join(format!("{name}.cu"))
                .display()
                .to_string(),
        );
        args
    }

    fn compile_artifact(
        &self,
        program: &Path,
        phase: Option<&str>,
        args: &[String],
        file_name: String,
        portable: bool,
    ) -> (String, u64) {
        let dependencies = if phase.is_some() {
            let output = cuda_command(program)
                .args(args)
                .args(["-M", "-MT", "kernel"])
                .output()
                .expect("read NVCC include dependencies");
            assert!(
                output.status.success(),
                "NVCC dependency generation for {file_name} failed:\n{}",
                String::from_utf8_lossy(&output.stderr)
            );
            dependency_paths(&output.stdout)
        } else {
            // The assembler consumes the already compiled, possibly downgraded
            // portable PTX; its bytes carry all original include dependencies.
            vec![self.out_dir.join(args.last().expect("PTX assembler input"))]
        };
        let mut hash = Sha256::new();
        hash.update(self.compiler_key);
        hash_field(&mut hash, phase.unwrap_or("ptxas").as_bytes());
        for argument in args {
            hash_field(&mut hash, argument.as_bytes());
        }
        if portable {
            hash_field(
                &mut hash,
                env::var_os("XLOG_PTX_MAX_VERSION")
                    .unwrap_or_default()
                    .as_encoded_bytes(),
            );
        }
        for path in dependencies {
            hash_field(&mut hash, path.as_os_str().as_encoded_bytes());
            hash.update(self.input_digest(&path));
        }
        let input_key: [u8; 32] = hash.finalize().into();
        let output = self.out_dir.join(&file_name);
        let fingerprint = self.out_dir.join(format!("{file_name}.fingerprint"));
        if let Ok(previous) = fs::read(&fingerprint) {
            if previous.len() == 40 && previous[..32] == input_key {
                if let Ok(bytes) = fs::read(&output) {
                    let artifact_hash = fnv1a_64(&bytes);
                    if !bytes.is_empty() && previous[32..] == artifact_hash.to_le_bytes() {
                        self.reused.fetch_add(1, Ordering::Relaxed);
                        return (file_name, artifact_hash);
                    }
                }
            }
        }

        // A failed or interrupted compiler must never leave a reusable entry.
        if fingerprint.exists() {
            fs::remove_file(&fingerprint).expect("invalidate kernel cache entry");
        }
        let temporary = self.out_dir.join(format!("{file_name}.partial"));
        let mut command = cuda_command(program);
        if let Some(phase) = phase {
            command.arg(phase);
        }
        let status = command
            .args(args)
            .arg("-o")
            .arg(&temporary)
            .status()
            .unwrap_or_else(|error| panic!("compile {file_name}: {error}"));
        assert!(status.success(), "CUDA compilation failed for {file_name}");
        if portable {
            maybe_downgrade_ptx_version(&temporary);
        }
        let bytes = fs::read(&temporary).expect("read compiled kernel artifact");
        assert!(!bytes.is_empty(), "compiler produced an empty {file_name}");
        let artifact_hash = fnv1a_64(&bytes);
        let mut entry = input_key.to_vec();
        entry.extend_from_slice(&artifact_hash.to_le_bytes());
        fs::rename(&temporary, &output).expect("publish compiled kernel artifact");
        let temporary_key = self
            .out_dir
            .join(format!("{file_name}.fingerprint.partial"));
        fs::write(&temporary_key, entry).expect("write kernel cache entry");
        fs::rename(temporary_key, fingerprint).expect("publish kernel cache entry");
        self.compiled.fetch_add(1, Ordering::Relaxed);
        (file_name, artifact_hash)
    }

    fn compile_module(&self, name: &str) -> Vec<(String, u64)> {
        let portable_name = format!("{name}.portable.ptx");
        let mut artifacts = vec![self.compile_artifact(
            &self.nvcc,
            Some("--ptx"),
            &self.nvcc_args(name, "sm_75"),
            portable_name.clone(),
            true,
        )];
        if !self.no_cubin {
            for arch in &self.cubin_archs {
                let file_name = format!("{name}.{arch}.cubin");
                artifacts.push(if let Some(ptxas) = &self.ptxas {
                    let mut args = vec![format!("-arch={arch}"), "-O3".to_owned()];
                    push_wcoj_register_cap(&mut args, name);
                    args.push(self.out_dir.join(&portable_name).display().to_string());
                    self.compile_artifact(ptxas, None, &args, file_name, false)
                } else {
                    self.compile_artifact(
                        &self.nvcc,
                        Some("--cubin"),
                        &self.nvcc_args(name, arch),
                        file_name,
                        false,
                    )
                });
            }
        }
        artifacts
    }
}

fn compile_kernels(
    compiler: &KernelCompiler,
    jobserver: Option<jobserver::Client>,
) -> Vec<(String, u64)> {
    let started = Instant::now();
    let mut modules = KERNEL_CU_NAMES.to_vec();
    // Start large translation units early so the final worker is less likely
    // to serialize the most expensive module after all the smaller jobs.
    modules.sort_by_cached_key(|name| {
        std::cmp::Reverse(
            fs::metadata(compiler.kernels_dir.join(format!("{name}.cu")))
                .expect("read kernel source size")
                .len(),
        )
    });
    let next = AtomicUsize::new(0);
    let failed = AtomicBool::new(false);
    let artifacts = Mutex::new(Vec::new());
    let (sender, receiver) = mpsc::channel();
    let receiver = Mutex::new(receiver);
    let jobs = env::var("NUM_JOBS")
        .expect("Cargo must supply NUM_JOBS")
        .parse::<usize>()
        .expect("Cargo NUM_JOBS must be a positive integer")
        .max(1)
        .min(modules.len());
    let run = |index: usize| {
        let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
            let compiled = compiler.compile_module(modules[index]);
            artifacts
                .lock()
                .expect("kernel result cache poisoned")
                .extend(compiled);
        }));
        if let Err(error) = result {
            failed.store(true, Ordering::Relaxed);
            std::panic::resume_unwind(error);
        }
    };
    std::thread::scope(|scope| {
        let helper = jobserver.filter(|_| jobs > 1).map(|client| {
            client
                .into_helper_thread(move |token| {
                    let _ = sender.send(token);
                })
                .expect("start Cargo job slot acquisition")
        });
        if let Some(helper) = &helper {
            for _ in 1..jobs {
                helper.request_token();
                scope.spawn(|| {
                    let _slot = match receiver.lock().expect("job slot receiver poisoned").recv() {
                        Ok(Ok(token)) => token,
                        Ok(Err(error)) => {
                            failed.store(true, Ordering::Relaxed);
                            panic!("acquire Cargo job slot: {error}");
                        }
                        Err(_) => return,
                    };
                    while !failed.load(Ordering::Relaxed) {
                        let index = next.fetch_add(1, Ordering::Relaxed);
                        if index >= modules.len() {
                            break;
                        }
                        run(index);
                    }
                });
            }
        }
        while !failed.load(Ordering::Relaxed) {
            let index = next.fetch_add(1, Ordering::Relaxed);
            if index >= modules.len() {
                break;
            }
            run(index);
        }
        // Slots can become available while the main thread compiles a large
        // kernel. The helper wakes waiting workers then, but is cancelled here
        // so an all-cache-hit build never waits for unrelated Cargo jobs.
        drop(helper);
    });
    for path in compiler
        .inputs
        .lock()
        .expect("kernel input cache poisoned")
        .keys()
    {
        if !path.starts_with(&compiler.out_dir) {
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }
    println!(
        "cargo:warning=CUDA artifacts: {} reused, {} compiled in {:.2}s",
        compiler.reused.load(Ordering::Relaxed),
        compiler.compiled.load(Ordering::Relaxed),
        started.elapsed().as_secs_f64()
    );
    artifacts
        .into_inner()
        .expect("kernel result cache poisoned")
}

fn write_semantic_value_schema(out_dir: &Path) {
    use xlog_ir::semantic_value::{
        SemanticValueFeedbackSchema, SEMANTIC_VALUE_ESTIMATORS, SEMANTIC_VALUE_RECEIPT_FIELDS,
        SEMANTIC_VALUE_SUPPORT_FIELDS,
    };

    let mut cuda = String::from("#pragma once\n#include <stdint.h>\nnamespace semantic_value {\n");
    for (name, fields) in [
        ("receipt", SEMANTIC_VALUE_RECEIPT_FIELDS),
        ("support", SEMANTIC_VALUE_SUPPORT_FIELDS),
    ] {
        cuda.push_str(&format!("namespace {name} {{\n"));
        for (index, field) in fields.iter().enumerate() {
            cuda.push_str(&format!("constexpr uint32_t {field}={index};\n"));
        }
        cuda.push_str(&format!("constexpr uint32_t words={};\n}}\n", fields.len()));
    }
    cuda.push_str("namespace feature {\n");
    let schema = SemanticValueFeedbackSchema::new(1).expect("semantic value feature schema");
    for field in schema.fields.iter().skip(1) {
        cuda.push_str(&format!(
            "constexpr uint32_t {}={};\n",
            field.name,
            field.offset - 9
        ));
    }
    cuda.push_str(&format!(
        "constexpr uint32_t tail_words={};\nconstexpr uint32_t estimators={};\n}}\n}}\n",
        schema.feature_width - 9,
        SEMANTIC_VALUE_ESTIMATORS.len()
    ));
    write_if_changed(out_dir.join("semantic_value_schema.cuh"), cuda)
        .expect("write semantic value kernel schema");
}

fn main() {
    // SAFETY: Cargo owns these inherited jobserver descriptors. Acquire the
    // client before opening files or starting children, and retain every extra
    // token until its worker has finished. The main thread uses Cargo's
    // implicit slot; an absent jobserver permits only serial compilation.
    let jobserver = unsafe { jobserver::Client::from_env() };
    println!("cargo:rerun-if-changed=build.rs");
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").unwrap())
        .canonicalize()
        .expect("resolve Cargo kernel output directory");
    write_semantic_transition_catalogue(&out_dir);
    write_semantic_value_schema(&out_dir);
    let semantic_policy = prepare_semantic_policy_header(&out_dir);
    let manifest_dir = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let kernels_dir = find_kernel_sources(&manifest_dir);
    println!("cargo:rerun-if-changed=src/kernel_manifest_data.rs");
    println!("cargo:rerun-if-changed={}", kernels_dir.display());
    println!("cargo:rerun-if-env-changed=XLOG_RUSTDOC_NO_CUDA");
    println!("cargo:rerun-if-env-changed=DOCS_RS");
    let build_flag = |name| {
        xlog_core::resolve_bool(None, name, false)
            .unwrap_or_else(|error| panic!("invalid CUDA build configuration: {error}"))
    };
    let docs_only = build_flag("XLOG_RUSTDOC_NO_CUDA") || build_flag("DOCS_RS");
    let no_cubin = build_flag("XLOG_NO_CUBIN");
    let cubin_archs: Vec<String> = env::var("XLOG_CUBIN_ARCHS")
        .unwrap_or_else(|_| "sm_120".to_string())
        .split(',')
        .map(str::trim)
        .filter(|arch| !arch.is_empty())
        .map(str::to_owned)
        .collect();
    for name in [
        "XLOG_NO_CUBIN",
        "XLOG_CUBIN_ARCHS",
        "NVCC_PATH",
        "XLOG_PTXAS_PATH",
        "XLOG_PTX_MAX_VERSION",
    ] {
        println!("cargo:rerun-if-env-changed={name}");
    }

    // Keep valid outputs. Remove only modules/targets no longer in this build
    // so staging and the wheel glob cannot collect obsolete artifacts.
    let mut expected = BTreeSet::new();
    if !docs_only {
        for name in KERNEL_CU_NAMES {
            expected.insert(format!("{name}.portable.ptx"));
            if !no_cubin {
                for arch in &cubin_archs {
                    expected.insert(format!("{name}.{arch}.cubin"));
                }
            }
        }
    }
    for entry in fs::read_dir(&out_dir).expect("read kernel output directory") {
        let entry = entry.expect("read kernel output entry");
        let file_name = entry.file_name().to_string_lossy().into_owned();
        let artifact = file_name.strip_suffix(".partial").unwrap_or(&file_name);
        let artifact = artifact.strip_suffix(".fingerprint").unwrap_or(artifact);
        if (artifact.ends_with(".cubin") || artifact.ends_with(".portable.ptx"))
            && (file_name.ends_with(".partial") || !expected.contains(artifact))
        {
            fs::remove_file(entry.path()).expect("remove obsolete kernel artifact");
        }
    }
    println!("cargo:kernel-out-dir={}", out_dir.display());
    if docs_only {
        write_empty_embedded_kernel_data(&out_dir);
        return;
    }

    let mut compiler = KernelCompiler {
        nvcc: resolve_compiler(&find_nvcc()),
        ptxas: find_ptxas_override().map(|path| resolve_compiler(&path)),
        out_dir,
        kernels_dir,
        cubin_archs,
        no_cubin,
        semantic_policy,
        compiler_key: [0; 32],
        inputs: Mutex::new(BTreeMap::new()),
        reused: AtomicUsize::new(0),
        compiled: AtomicUsize::new(0),
    };
    compiler.compiler_key = compiler.compiler_identity();
    let artifacts = compile_kernels(&compiler, jobserver);
    write_embedded_kernel_data(&compiler.out_dir, artifacts);
}

/// Rewrite the `.version` directive of a portable PTX file to the ISA named by
/// XLOG_PTX_MAX_VERSION (no-op when unset or already lower).
fn maybe_downgrade_ptx_version(ptx_path: &Path) {
    println!("cargo:rerun-if-env-changed=XLOG_PTX_MAX_VERSION");
    let target = match env::var("XLOG_PTX_MAX_VERSION") {
        Ok(v) if !v.trim().is_empty() => v.trim().to_string(),
        _ => return,
    };
    let text = fs::read_to_string(ptx_path)
        .unwrap_or_else(|e| panic!("read PTX {}: {e}", ptx_path.display()));
    let mut out = String::with_capacity(text.len());
    let mut rewritten = false;
    for line in text.lines() {
        let trimmed = line.trim_start();
        if !rewritten && trimmed.starts_with(".version ") {
            let indent = &line[..line.len() - trimmed.len()];
            out.push_str(&format!("{indent}.version {target}\n"));
            rewritten = true;
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    fs::write(ptx_path, out)
        .unwrap_or_else(|e| panic!("write downgraded PTX {}: {e}", ptx_path.display()));
}

