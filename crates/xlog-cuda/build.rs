                assert!(prepare_semantic_policy_header(&output));
                assert!(identities
                    .insert(fs::read(output.join("semantic_policy_identity.rs")).unwrap()));
                env::set_var(variables[3], namespace);
                assert!(prepare_semantic_policy_header(&output));
